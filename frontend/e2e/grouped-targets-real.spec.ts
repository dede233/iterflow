import { expect, test } from '@playwright/test'
// This suite is opt-in and only accepts the newly created local task preview.
for (const width of [1440, 375]) test(`isolated real grouped mini program at ${width}px`, async ({ page, request, baseURL }) => {
  test.skip(process.env.ITERFLOW_GROUPED_REAL !== '1', 'Explicit disposable local environment required')
  expect(baseURL).toBe('http://127.0.0.1:57423')
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const login = await request.post('/api/v1/auth/login', { data: { username: 'grouped-preview', password: 'Grouped-preview-password!' } })
  expect(login.status()).toBe(200)
  const tokens = await login.json(), headers = { Authorization: `Bearer ${tokens.access_token}` }
  const systems = await request.get('/api/v1/systems/manage', { headers })
  const sid = (await systems.json()).systems.find((s: any) => s.code === `GROUPED_UI_${width}`).id
  const legacy = await request.post(`/api/v1/systems/${sid}/release-targets`, { headers, data: { code: `GROUPED_REAL_${width}_WX`, name: `合成品牌 ${width}`, platform: 'WECHAT_MINI_PROGRAM', app_id: 'wx1234567890abcdef' } })
  expect(legacy.status()).toBe(201)
  const old = await legacy.json()
  await page.addInitScript(({ access, refresh }) => { localStorage.setItem('iterflow.access_token', access); localStorage.setItem('iterflow.refresh_token', refresh) }, { access: tokens.access_token, refresh: tokens.refresh_token })
  await page.setViewportSize({ width, height: width === 375 ? 812 : 1000 })
  await page.goto('/#/admin/systems')
  // Prefer the visible system button in both desktop tables and mobile cards.
  await page.getByRole('button', { name: `编辑系统 Isolated grouped UI ${width}`, exact: true }).waitFor()
  const editSystem = page.getByRole('button', { name: `编辑系统 Isolated grouped UI ${width}`, exact: true })
  await editSystem.locator('..').getByRole('button', { name: '发布目标', exact: true }).click()
  await page.getByRole('button', { name: `编辑发布目标 合成品牌 ${width}`, exact: true }).click()
  const editor = page.getByRole('dialog', { name: '编辑发布目标', exact: true })
  await expect(editor.getByRole('textbox', { name: '目标编码' })).toHaveValue(`GROUPED_REAL_${width}`)
  await editor.getByText('支付宝小程序', { exact: true }).click()
  await editor.getByRole('textbox', { name: '支付宝小程序 AppID', exact: true }).fill('2021000000000001')
  await page.screenshot({ path: test.info().outputPath(`real-brand-form-${width}.png`), fullPage: true, animations: 'disabled' })
  await editor.getByRole('button', { name: '保存目标', exact: true }).click(); await expect(editor).toBeHidden()
  const manager = page.getByRole('dialog', { name: '管理发布目标', exact: true })
  await expect(manager.locator('.target')).toHaveCount(1)
  await expect(manager).toContainText('微信小程序'); await expect(manager).toContainText('支付宝小程序')
  const catalog = await (await request.get(`/api/v1/systems/${sid}/release-targets`, { headers })).json()
  expect(catalog).toHaveLength(2); expect(catalog.find((t: any) => t.platform === 'WECHAT_MINI_PROGRAM').id).toBe(old.id)
  await page.goto('/#/versions')
  const versions = await (await request.get('/api/v1/versions?page=1&page_size=50', { headers })).json()
  const version = versions.items.find((v: any) => v.version_no === `UI-GROUPED-${width}`)
  await page.goto(`/#/versions/${version.id}`)
  await page.getByRole('button', { name: '发布版本', exact: true }).click()
  const publish = page.getByRole('dialog', { name: '发布版本', exact: true })
  await publish.getByRole('region', { name: `合成品牌 ${width}发布平台`, exact: true }).getByText('微信小程序', { exact: true }).click()
  await publish.getByRole('textbox', { name: '发布说明', exact: true }).fill('Isolated real WeChat release')
  await publish.getByRole('button', { name: '确认发布', exact: true }).click(); await expect(publish).toBeHidden()
  const before = await (await request.get('/api/v1/releases?page=1&page_size=50', { headers })).json()
  const release = before.items.find((r: any) => r.version_id === version.id)
  expect(release).toBeTruthy()
  await page.getByRole('button', { name: '补记已发布目标', exact: true }).click()
  const supplement = page.getByRole('dialog', { name: '补记已发布目标', exact: true })
  await expect(supplement.getByRole('checkbox', { name: `合成品牌 ${width} · 微信小程序（已记录）`, exact: true })).toBeDisabled()
  await expect(supplement.getByRole('checkbox', { name: `合成品牌 ${width} · 支付宝小程序`, exact: true })).not.toBeChecked()
  await supplement.getByRole('region', { name: `合成品牌 ${width}发布平台`, exact: true }).getByText('支付宝小程序', { exact: true }).click()
  await page.screenshot({ path: test.info().outputPath(`real-platform-selection-${width}.png`), fullPage: true, animations: 'disabled' })
  await supplement.getByRole('button', { name: '保存已发布目标', exact: true }).click(); await expect(supplement).toBeHidden()
  const after = await (await request.get('/api/v1/releases?page=1&page_size=50', { headers })).json()
  expect(after.items.filter((r: any) => r.version_id === version.id)).toEqual([release])
  const batches = await (await request.get(`/api/v1/versions/${version.id}/release-batches`, { headers })).json()
  expect(batches.coverage_count).toBe(2)
  expect(batches.items.flatMap((b: any) => b.targets).every((r: any) => r.completed_at)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({ path: test.info().outputPath(`real-final-${width}.png`), fullPage: true, animations: 'disabled' })
})
